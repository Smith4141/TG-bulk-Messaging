export function getLanguageByCode(code: string): WebsiteLanguage {
  return (
    WEBSITE_LANGUAGES.find((l) => l.code === code) ||
    WEBSITE_LANGUAGES.find((l) => l.code === 'en')!
  );
}

export function resolveDetectedLanguage(): WebsiteLanguage {
  if (typeof navigator === 'undefined') {
    return getLanguageByCode('en');
  }
  const browserLangs = navigator.languages?.length
    ? navigator.languages
    : [navigator.language || 'en'];

  for (const raw of browserLangs) {
    const normalized = raw.trim();
    if (!normalized) continue;
    const exact = WEBSITE_LANGUAGES.find(
      (l) => !l.isAuto && l.code.toLowerCase() === normalized.toLowerCase()
    );
    if (exact) return exact;

    const base = normalized.split('-')[0].toLowerCase();
    if (base === 'zh') {
      const lower = normalized.toLowerCase();
      if (lower.includes('tw') || lower.includes('hk') || lower.includes('hant')) {
        return getLanguageByCode('zh-TW');
      }
      return getLanguageByCode('zh-CN');
    }
    if (base === 'he') return getLanguageByCode('iw');
    if (base === 'jv') return getLanguageByCode('jw');

    const baseMatch = WEBSITE_LANGUAGES.find(
      (l) => !l.isAuto && l.code.toLowerCase() === base
    );
    if (baseMatch) return baseMatch;
  }

  return getLanguageByCode('en');
}
